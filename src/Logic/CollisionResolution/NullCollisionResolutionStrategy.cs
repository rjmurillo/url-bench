using Logic.Contracts;

namespace Logic.CollisionResolution;

/// <summary>
/// A null collision resolution strategy that doesn't modify the base short URL.
/// This strategy is suitable for systems where collision probability is extremely low
/// or when no collision resolution is desired (e.g., single-instance deployments with deterministic shorteners).
/// </summary>
public class NullCollisionResolutionStrategy : ICollisionResolutionStrategy
{
    /// <summary>
    /// Generates a unique short URL by returning the base short URL unchanged.
    /// </summary>
    /// <param name="baseShortUrl">The base short URL generated by the primary shortener.</param>
    /// <param name="attempt">The current attempt number (0-based).</param>
    /// <param name="longUrl">The original long URL being shortened.</param>
    /// <returns>The base short URL unchanged.</returns>
    public string GenerateUniqueShortUrl(string baseShortUrl, int attempt, string longUrl)
    {
        ArgumentException.ThrowIfNullOrEmpty(baseShortUrl);
        ArgumentException.ThrowIfNullOrEmpty(longUrl);

        if (attempt < 0)
        {
            throw new ArgumentOutOfRangeException(nameof(attempt), "Attempt number must be non-negative.");
        }

        // Always return the base short URL unchanged
        return baseShortUrl;
    }
}
